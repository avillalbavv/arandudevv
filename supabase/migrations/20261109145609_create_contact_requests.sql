create table public.contact_requests (
  id bigint generated by default as identity primary key,
  full_name text not null check (char_length(full_name) between 2 and 120),
  email text not null check (char_length(email) between 5 and 254),
  organization text check (organization is null or char_length(organization) <= 160),
  phone text check (phone is null or char_length(phone) <= 40),
  message text not null check (char_length(message) between 10 and 4000),
  source text not null default 'website' check (source = 'website'),
  status text not null default 'new' check (status in ('new','contacted','closed','spam')),
  created_at timestamptz not null default now()
);

alter table public.contact_requests enable row level security;
revoke all on table public.contact_requests from anon, authenticated;
grant insert (full_name, email, organization, phone, message, source)
on table public.contact_requests to anon, authenticated;

create policy "public_can_submit_contact_requests"
on public.contact_requests for insert to anon, authenticated
with check (
  source = 'website'
  and status = 'new'
  and char_length(full_name) between 2 and 120
  and char_length(email) between 5 and 254
  and char_length(message) between 10 and 4000
);
